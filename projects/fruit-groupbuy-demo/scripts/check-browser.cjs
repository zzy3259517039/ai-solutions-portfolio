// 需要 Playwright。此脚本使用正在运行的本机演示服务。
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.BROWSER_CHANNEL?{channel:process.env.BROWSER_CHANNEL}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1080}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const failed=[]; page.on('requestfailed',r=>failed.push(r.url()));
  const dir=path.join(__dirname,'../screenshots');fs.mkdirSync(dir,{recursive:true});
  await page.goto('http://127.0.0.1:8766');
  await page.locator('.product-card').first().waitFor();
  await page.screenshot({path:path.join(dir,'01-desktop-home.png'),fullPage:true});
  await page.locator('[data-action="detail"][data-id="family"]').click();
  await page.locator('[data-action="checkout"]').click();
  assert.equal(await page.locator('#pay-button').isDisabled(),true);
  await page.locator('#agree').check();
  await page.locator('#pay-button').click();
  assert.match(await page.locator('.success-head').innerText(),/模拟购买成功/);
  const code=(await page.locator('.ticket-code').innerText()).replace(/\s/g,'');
  assert.match(code,/^\d{8}$/);
  await page.screenshot({path:path.join(dir,'02-coupon.png'),fullPage:true});
  await page.locator('[data-action="handoff"]').click();
  assert.equal(await page.locator('#redeem-code').inputValue(),code);
  await page.locator('[data-action="lookup"]').click();
  await page.locator('#redeem-code').fill('00000000');
  assert.equal(await page.locator('[data-action="redeem"]').count(),0);
  await page.locator('#redeem-code').fill(code);
  await page.locator('[data-action="lookup"]').click();
  await page.locator('[data-action="redeem"]').click();
  await page.locator('[data-action="confirm-redeem"]').click();
  assert.match(await page.locator('.lookup-card').innerText(),/已经核销/);
  assert.equal(await page.locator('[data-action="redeem"]').count(),0);
  await page.screenshot({path:path.join(dir,'03-merchant-redeemed.png'),fullPage:true});
  await page.reload();
  await page.locator('[data-view="orders"]').click();
  assert.match(await page.locator('.order-card').innerText(),/已提货/);
  await page.locator('[data-action="go"][data-view="home"]').first().click();
  await page.locator('[data-action="detail"][data-id="orange"]').click();
  await page.locator('[data-action="checkout"]').click();
  await page.locator('#agree').check();await page.locator('#pay-button').click();
  const refundedCode=(await page.locator('.ticket-code').innerText()).replace(/\s/g,'');
  await page.locator('[data-action="refund"]').click();
  await page.locator('[data-action="confirm-refund"]').click();
  assert.match(await page.locator('.success-head').innerText(),/已模拟退款/);
  await page.locator('#role-merchant').click();
  await page.locator('#redeem-code').fill(refundedCode);await page.locator('[data-action="lookup"]').click();
  assert.match(await page.locator('.lookup-card').innerText(),/已模拟退款/);
  assert.equal(await page.locator('[data-action="redeem"]').count(),0);
  await page.locator('#redeem-code').fill('00000000');await page.locator('[data-action="lookup"]').click();
  assert.match(await page.locator('.inline-error').innerText(),/未找到/);
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto('http://127.0.0.1:8766');
  await mobile.locator('.product-card').first().waitFor();
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await mobile.screenshot({path:path.join(dir,'04-mobile-home.png'),fullPage:true});
  await mobile.locator('[data-id="apple"]').click();
  await mobile.locator('[data-action="checkout"]').click();
  await mobile.locator('#agree').check();await mobile.locator('#pay-button').click();
  await mobile.locator('[data-action="handoff"]').click();await mobile.locator('[data-action="lookup"]').click();
  await mobile.locator('[data-action="redeem"]').click();await mobile.locator('[data-action="confirm-redeem"]').click();
  await mobile.screenshot({path:path.join(dir,'05-mobile-merchant.png'),fullPage:true});
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  assert.deepEqual(errors,[]);assert.deepEqual(failed,[]);
  console.log('PASS: desktop purchase, consent, coupon, redemption, reload persistence, refund, invalid code; mobile purchase/redemption and no horizontal overflow; zero browser JS errors.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
