CREATE TABLE IF NOT EXISTS refunds (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  order_id BIGINT UNSIGNED NOT NULL,
  out_refund_no VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  amount INT UNSIGNED NOT NULL,
  reason VARCHAR(80) NOT NULL,
  status ENUM('REQUESTED', 'PROCESSING', 'SUCCESS', 'CLOSED', 'ABNORMAL') NOT NULL DEFAULT 'REQUESTED',
  wechat_refund_id VARCHAR(64) NULL,
  requested_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  completed_at DATETIME(3) NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_refunds_order (order_id),
  UNIQUE KEY uq_refunds_no (out_refund_no),
  CONSTRAINT fk_refunds_order FOREIGN KEY (order_id) REFERENCES orders(id),
  CONSTRAINT chk_refunds_amount CHECK (amount > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
