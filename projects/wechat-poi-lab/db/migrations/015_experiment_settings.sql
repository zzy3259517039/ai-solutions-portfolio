CREATE TABLE IF NOT EXISTS experiment_settings (
  id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
  store_id BIGINT UNSIGNED NULL,
  poi_name VARCHAR(120) NOT NULL DEFAULT '',
  poi_address VARCHAR(255) NOT NULL DEFAULT '',
  poi_status VARCHAR(40) NOT NULL DEFAULT 'NOT_STARTED',
  location_entry VARCHAR(120) NOT NULL DEFAULT '',
  service_name VARCHAR(120) NOT NULL DEFAULT '团购',
  mini_path VARCHAR(255) NOT NULL DEFAULT '',
  path_params VARCHAR(255) NOT NULL DEFAULT '',
  review_status VARCHAR(40) NOT NULL DEFAULT 'NOT_SUBMITTED',
  merchant_confirmed_at DATETIME(3) NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_experiment_store FOREIGN KEY (store_id) REFERENCES stores(id),
  CONSTRAINT chk_experiment_id CHECK (id = 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
